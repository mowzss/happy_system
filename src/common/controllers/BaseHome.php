<?php
declare (strict_types=1);


namespace app\common\controllers;

use app\logic\system\System;
use think\App;
use think\facade\View;

class BaseHome extends Base
{
    /**
     * @var array $url_info 当前页面 URL 信息
     * fetch() 会自动把控制器属性注入模板，模板中直接使用 {$url_info.pc_url} 等
     */
    protected array $url_info = [];

    public function __construct(App $app)
    {
        parent::__construct($app);
        $this->app->event->trigger('HomeControllerInit');
    }

    /**
     * 初始化设置
     * @return void
     * @throws \Throwable
     */
    protected function initialize(): void
    {
        parent::initialize(); // TODO: Change the autogenerated stub
        // 注意：closeSite() 通过抛出 HttpResponseException 中断并输出响应，
        // 该异常属于 \Throwable，严禁被 catch 吞掉，否则闭站提示不会生效。
        // 因此仅在 try 内做配置读取，闭站调用移到 try 外正常冒泡。
        $siteClosed = false;
        if ($this->app->config->get('happy.installed', false)) {
            try {
                $siteClosed = (int)sys_config('is_open_site') === 0;
            } catch (\Throwable $e) {
                $this->app->log->error($e->getMessage(), $e->getTrace());
            }
        }

        if ($siteClosed) {
            $this->closeSite('网站暂未开启!敬请期待');
        }
        $this->url_info = System::instance()->getUrlInfo();
    }

    /**
     * 标准化页面 TDK：统一并入 $info 的 seo_title / seo_keywords / seo_description 三个字段
     * - seo_title 不含品牌词（品牌词由布局 head_title_suffix 块统一输出）
     * - 回退链：seo_title -> title；seo_keywords -> keywords -> seo_title；seo_description -> description -> content 摘要 -> seo_title
     * @param array $info
     * @return array
     */
    protected function normalizeSeoInfo(array $info): array
    {
        if (empty($info)) {
            return $info;
        }
        $info['seo_title'] = trim((string)($info['seo_title'] ?? '')) ?: trim((string)($info['title'] ?? ''));
        $info['seo_keywords'] = trim((string)($info['seo_keywords'] ?? '')) ?: trim((string)($info['keywords'] ?? '')) ?: $info['seo_title'];
        $description = trim((string)($info['seo_description'] ?? '')) ?: trim((string)($info['description'] ?? ''));
        if ($description === '' && !empty($info['content'])) {
            $description = (string)get_word(del_html($info['content']), 120);
        }
        $info['seo_description'] = $description !== '' ? $description : $info['seo_title'];
        return $info;
    }

    protected function fetch(string $template = '', array $vars = []): string
    {
        if ($this->request->isAjax()) {
            $baseTemplate = empty($template) ? $this->request->action(true) : $template;
            $ajaxTemplate = $baseTemplate . '_ajax';

            if (View::exists($ajaxTemplate)) {
                return parent::fetch($ajaxTemplate, $vars);
            }
        }

        return parent::fetch($template, $vars);
    }
}
