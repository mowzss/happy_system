<?php
declare (strict_types=1);


namespace app\common\util;

use app\logic\system\ConfigLogic;
use GuzzleHttp\Exception\GuzzleException;
use happy\admin\libs\baidu\AipNlpKeyword;
use happy\admin\libs\baidu\AipNlpSummary;
use HTMLPurifier;
use HTMLPurifier_Config;
use mowzs\cms\logic\FieldBaseLogic;
use mowzs\cms\logic\TagBaseLogic;
use think\db\exception\DataNotFoundException;
use think\db\exception\DbException;
use think\db\exception\ModelNotFoundException;
use think\Exception;
use think\facade\Log;

class ContentSaveFilterUtil extends UtilBase
{
    /**
     * 当前模块配置
     * @var mixed
     */
    protected mixed $config;
    /**
     * 网站配置
     * @var mixed
     */
    protected mixed $web_config;

    /**
     * 初始化
     * @return void
     * @throws DataNotFoundException
     * @throws DbException
     * @throws ModelNotFoundException
     */
    protected function initialize(): void
    {
        parent::initialize(); // TODO: Change the autogenerated stub
        $this->web_config = ConfigLogic::instance()->getConfigValue();
        $this->config = $this->web_config[$this->app->request->layer(true)];
    }

    /**
     * 校验是否开启下载图片
     * @return bool
     */
    protected function isDownImage(): bool
    {
        if (!empty($this->config['is_content_image_down'])) {
            return true;
        }
        return false;
    }

    /**
     * 检测是否开启获取缩略图
     * @return bool
     */
    protected function isImagesThum(): bool
    {
        if (!empty($this->config['is_content_thum'])) {
            return true;
        }
        return false;
    }

    /**
     * 检测是否开启内容过滤
     * @return bool
     */
    protected function isPuriferHtml(): bool
    {
        if (!empty($this->config['is_content_purifer_html'])) {
            return true;
        }
        return false;
    }

    /**
     * 检查排除域名
     * @param string $url
     * @return bool
     */
    protected function isDownFilterHost(string $url = ''): bool
    {
        $host = match ($this->web_config['system']['storage_driver']) {
            'oss' => $this->web_config['system']['oss_domain'],
            'qiniu' => $this->web_config['system']['qiniu_domain'],
            default => $this->app->request->host(true),
        };
        return stripos($url, $host) !== false;
    }

    /**
     * 检测功能是否开启
     * @return bool
     */
    protected function cheek(): bool
    {
        if ($this->isDownImage()) {
            return true;
        }
        if ($this->isImagesThum()) {
            return true;
        }
        if ($this->isPuriferHtml()) {
            return true;
        }
        return false;
    }

    /**
     * 内容过滤
     * @param string $content
     * @return string
     */
    public function purifierContent(string $content): string
    {
        $config = HTMLPurifier_Config::createDefault();
        //设置允许出现的html标签
        $config->set('HTML.Allowed', $this->config['content_purifer_html'] ?? 'h2,h3,h4,h5,p,strong,a[href|title],span[style],img[width|height|alt|src],table');
        // 设置允许出现的CSS样式属性
        $config->set(
            'CSS.AllowedProperties',
            $this->config['content_purifer_css'] ?? 'font,font-size,font-weight,font-style,font-family,text-decoration,padding-left,color,background-color,text-align'
        );
        $config->set('AutoFormat.RemoveEmpty', (bool)$this->config['content_purifer_remove_empty']);
        return (new HTMLPurifier($config))->purify($content);
    }

    /**
     * 处理数据
     * @param $info
     * @return array
     * @throws Exception|\happy\admin\libs\Exception\LogicException|GuzzleException
     */
    public function setProcessingData($info): array
    {
        $info = $this->setTag($info);
        $info = $this->setDescription($info);
        $info = $this->setCheckboxData($info);
        $update = [];
        //检测功能是否开启
        if ($this->cheek()) {
            if (!empty($info['content'])) {
                //过滤内容
                if ($this->isPuriferHtml()) {
                    $update['content'] = $info['content'] = $this->purifierContent($info['content']);
                }
                $pattern = "/<img[^>]*src=[\'\"]((?:https?:)?\/\/[^\s\'\"]+\.(?:gif|jpg|png|jpeg|webp))[\'\"][^>]*>/i";
                preg_match_all($pattern, $info['content'], $images);
                $newContent = $info['content'];
                //下载远程图片
                if ($this->isDownImage()) {
                    foreach ($images[1] as $image) {
                        $oldSrc = $image;
                        if (!$this->isDownFilterHost($oldSrc)) {
                            try {
                                $file_info = (new RemoteFileUtil)->downloadAndSave($oldSrc);
                                $newSrc = $file_info['url'];
                            } catch (\Exception $e) {
                                Log::error('保存远程图片失败:' . $e->getMessage());
                                $newSrc = $oldSrc;
                            }
                            $newContent = str_replace($oldSrc, $newSrc, $newContent);
                        }
                    }
                    $update['content'] = $info['content'] = $newContent;
                }
                //处理缩略图
                if ($this->isImagesThum()) {
                    preg_match_all($pattern, $info['content'], $images);
                    $info_images = $images[1];
                    if (count($info_images) > $this->config['is_content_thum_num']) {
                        $info_images = array_slice($info_images, 0, (int)$this->config['is_content_thum_num']);
                    }
                    if (!empty($info_images)) {
                        $picurl = implode(',', $info_images);
                        $ispic = 1;
                    }
                    $update['images'] = $picurl ?? '';
                    $update['is_pic'] = $ispic ?? 0;
                }
            }
            return array_merge($info, $update);
        }
        return $info;
    }

    protected function setCheckboxData($info)
    {
        if (!empty($info['mid'])) {
            $fields = FieldBaseLogic::instance()->getFieldsInfoByType((int)$info['mid'], 'checkbox');
            if (!empty($fields)) {
                foreach ($fields as $field) {
                    $info[$field['name']] = arr2str($info[$field['name']]);
                }
            }
        }
        return $info;
    }

    /**
     * 设置描述
     * @param $data
     * @return mixed
     * @throws Exception
     * @throws GuzzleException
     */
    protected function setDescription($data): mixed
    {
        // 防御：绕过前端直接提交时 title/content 可能缺失，避免 Undefined array key
        // 必填校验由控制器的 checkRequiredFields() 负责，这里只保证不因缺键抛出 500
        $title = (string)($data['title'] ?? '');
        $content = (string)($data['content'] ?? '');
        if (empty($data['description']) && $title !== '' && $content !== '') {
            $data['description'] = (new AipNlpSummary())->getSummary($title, get_word(del_html($content), 1500));
            $data['description'] = $data['description'] ?: get_word(del_html($content), 200);
        }
        return $data;
    }

    /**
     * 当前模块是否开启百度自动生成 TAG
     * 未配置该开关时默认开启，保持升级前的行为
     * @return bool
     */
    protected function isOpenBaiduTag(): bool
    {
        return (string)($this->config['is_open_baidu_tag'] ?? '1') === '1';
    }

    /**
     * @param $data
     * @return mixed
     * @throws Exception|\happy\admin\libs\Exception\LogicException
     */
    protected function setTag($data): mixed
    {
        // 后台正常提交由 xmselect 提供 tag 关联 id；huati 为 publish/采集传入的文字标签
        $title = (string)($data['title'] ?? '');
        $content = (string)($data['content'] ?? '');
        if (empty($data['huati']) && empty($data['tag']) && ($title !== '' || $content !== '')
            && $this->isOpenBaiduTag()) {
            // 无语义内容时不再请求外部接口
            $data['huati'] = (new AipNlpKeyword())->getStringTag(
                $title,
                get_word(del_html($content), 800)
            );
        }
        //处理tag
        $tags = [];
        if (!empty($data['huati']) && empty($data['tag'])) {
            // 显式指定模块，避免静态 module 在跨模块请求中被复用
            $tagLogic = TagBaseLogic::instance([$this->app->request->layer(true)]);
            $huati = str2arr($data['huati']);
            foreach ($huati as $k => $v) {
                if ($v === '') {
                    continue;
                }
                $tags[$k] = $tagLogic->getTagIdByTitle($v);
            }
            $data['tag'] = arr2str($tags);
        }
        return $data;
    }
}
